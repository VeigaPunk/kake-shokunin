#!/usr/bin/env python3
"""Build .ufo/waves/round-100/frozen/: the C2 positive oracle (the counter's REF block wrapped
as a standalone stdin->stdout program) and one forgery per v2 clause / escape class, each a
single textual mutation of the oracle that must apply exactly once. Run before the freeze."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, "c100_fresh304.py")).read()
ref = src.split("# --- REF BEGIN\n", 1)[1].split("# --- REF END\n", 1)[0]
MAIN = '''

def main():
    data = sys.stdin.buffer.read()
    try:
        out = decide_bytes(data)
    except Refuse as e:
        sys.stderr.write("invalid_input: %s\\n" % e)
        return 1
    sys.stdout.write(json.dumps(out) + "\\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
'''
oracle = "#!/usr/bin/env python3\n# round-100 C2 positive oracle (generated by build_frozen.py)\nimport json\nimport sys\n" + ref + MAIN

THEFT = '''#!/usr/bin/env python3
# round-100 forgery: oracle theft through the parent process (SentinelScope W1 vector).
import importlib.util, json, os, sys
data = sys.stdin.buffer.read()
try:
    argv = open("/proc/%d/cmdline" % os.getppid(), "rb").read().split(b"\\0")
    path = [a.decode() for a in argv if a.endswith(b"c100_fresh304.py")][0]
    spec = importlib.util.spec_from_file_location("ctr", path)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    try:
        out = m.decide_bytes(data)
    except m.Refuse as e:
        sys.stderr.write("invalid_input: %s\\n" % e)
        sys.exit(1)
    sys.stdout.write(json.dumps(out) + "\\n")
    sys.exit(0)
except SystemExit:
    raise
except Exception:
    sys.stdout.write("{}\\n")
    sys.exit(0)
'''

MUT = {
    # F1: only the quoted-string argument form counts as qualified
    "neg-f1-tokenform": ('            out.append((name, has_arg))\n',
                         '            out.append((name, has_arg and v[i - 1] == \'"\'))\n'),
    # F10: v1 substring test instead of a parsed directive name
    "neg-f10-substring": ('            if has_arg and name in ("no-cache", "private"):\n',
                          '            if has_arg and any(name.endswith(q) for q in ("no-cache", "private")):\n'),
    # LC6 case: directive names compared case-sensitively
    "neg-lc6-case": ('            name = m.group(0).lower()\n', '            name = m.group(0)\n'),
    # V2-1a: malformed Cache-Control ignored instead of refused
    "neg-malformed-lenient": ('        for name, has_arg in _cc_directives(rh["cache-control"]):\n',
                              '        try:\n            dirs = _cc_directives(rh["cache-control"])\n        except Refuse:\n            dirs = []\n        for name, has_arg in dirs:\n'),
    # F2: values copied byte-for-byte (v1 behaviour)
    "neg-f2-notrim": ('{k: v.strip(OWS) for k, v in h.items()}', 'dict(h)'),
    # F3: stored proxy-specific fields kept
    "neg-f3-keepproxy": ('if k not in PROXY}', 'if True}'),
    # e1: stored connection / hop-by-hop fields stripped too
    "neg-e1-striphop": ('if k not in PROXY}', 'if k not in PROXY | HOP | {"connection"}}'),
    # e2: stored ETags validated only when the 304 carries an ETag
    "neg-e2-lazy": ('        et = _etag(sh["etag"]) if "etag" in sh else None\n',
                    '        et = _etag(sh["etag"]) if "etag" in sh and "etag" in rh else (( False, sh["etag"].strip(OWS).strip(\'"\')) if "etag" in sh else None)\n'),
    # e3: Last-Modified trimmed of spaces only
    "neg-e3-spaceonly": ('        lm = sh["last-modified"].strip(OWS) if', '        lm = sh["last-modified"].strip(" ") if'),
    # e4: a newline on stdout with a refusal
    "neg-e4-wsstdout": ('        sys.stderr.write("invalid_input: %s\\n" % e)\n',
                        '        sys.stdout.write("\\n")\n        sys.stderr.write("invalid_input: %s\\n" % e)\n'),
    # e5: invalid JSON crashes with a traceback
    "neg-e5-crash": ('    except (UnicodeDecodeError, ValueError, RecursionError):\n        raise Refuse("invalid json")\n',
                     '    except RecursionError:\n        raise Refuse("invalid json")\n'),
    # e6: Age withheld from the copy
    "neg-e6-ageexcl": ('    excl = {"content-length", "connection"} | HOP | PROXY\n',
                       '    excl = {"content-length", "connection", "age"} | HOP | PROXY\n'),
    # e7: tie refused only when the 304 carries an ETag
    "neg-e7-lmtie": ('            if len(best) > 1:\n', '            if len(best) > 1 and ret is not None:\n'),
}


def main():
    out = os.path.join(HERE, "frozen")
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "pos-oracle.py"), "w").write(oracle)
    open(os.path.join(out, "neg-theft.py"), "w").write(THEFT)
    for name, (a, b) in sorted(MUT.items()):
        n = oracle.count(a)
        if n != 1:
            print("mutation %s applies %d times" % (name, n), file=sys.stderr)
            return 2
        open(os.path.join(out, name + ".py"), "w").write(oracle.replace(a, b))
    print("built pos-oracle + neg-theft + %d mutations" % len(MUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
