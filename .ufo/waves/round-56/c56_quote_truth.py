            if not re.search(rf"\b{sid}\b", src):
                c2.append(f"{sid}: `source:` line does not name {sid}")
            if not any(re.search(rf"\b{sid}\b", ln) for ln in lines[8:]):
                c2.append(f"{sid}: entry does not cite its id below the 8-line header")
            vline = next((ln for ln in head if re.match(r"^[-* ]*verified-at *:", ln)), "")
            if ROUND_DATE not in vline:
                c2.append(f"{sid}: `verified-at:` line does not carry the round date {ROUND_DATE}")
            rline = next((ln for ln in head if re.match(r"^[-* ]*recheck *:", ln)), "")
            if not re.match(r"^[-* ]*recheck *:\s*(\d+d|\d{4}-\d{2}-\d{2}|on-release)\b", rline):
                c2.append(f"{sid}: `recheck:` line does not open with NNd, an ISO date or on-release")
