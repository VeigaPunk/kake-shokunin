def main() -> int:
    class _Parser(argparse.ArgumentParser):
        def error(self, message):
            print(f"usage error: {message}", file=sys.stderr)
            raise SystemExit(64)

    ap = _Parser(description="Round-58 C3 counter (Baidu crawler-identification entries)")
    ap.add_argument("--root", default=".")
    ap.add_argument("--base", default=BASE_REV, help="the base revision holding the pre-append registry (default: the frozen one)")
    ap.add_argument("--revision")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    if not args.revision:
        print("usage: --revision is required unless --selftest is used", file=sys.stderr)
        return 64
    if git(args.root, "rev-parse", "--verify", "--quiet", f"{args.revision}^{{commit}}")[0] != 0:
        print(f"unevaluable: revision {args.revision!r} does not resolve in {args.root!r}")
        print("EXIT=2")
        return 2
    code, results = run_checks(args.root, args.revision, args.base)
    passed = sum(1 for r in results if r["state"] == "pass")
    if args.json:
        print(json.dumps({
            "schema": "kake-r58-c3-quote-truth-v1", "predicate": PREDICATE, "revision": args.revision,
            "adopted": ADOPTED,
            "checks": {r["check"]: {"passed": r["state"] == "pass", "state": r["state"],
                                    "notes": r["notes"], "facts": r["facts"]} for r in results},
            "conditions_passed": passed, "exit": code, "met": code == 0}, indent=1, ensure_ascii=False))
        return code
    else:
        print(f"C3 quote-truth {passed}/8 met={code == 0}  ({PREDICATE})")
        for r in results:
            print(f"  {r['check']} {r['state'].upper()}")
            for note in r["notes"]:
                print(f"    - {note}")
        print(f"  revision: {args.revision}")
    print(f"EXIT={code}")
    return code


if __name__ == "__main__":
    sys.exit(main())
