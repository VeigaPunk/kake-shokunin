def git(root: str, *args: str) -> tuple[int, str]:
    proc = subprocess.run(["git", "-C", root, *args], stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, text=True, env=clean_env())
    return proc.returncode, proc.stdout


def show(root: str, rev: str, path: str) -> str | None:
    """Byte-exact: UTF-8 strict decode, no newline translation."""
    raw = show_bytes(root, rev, path)
    if raw is None:
        return None
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return None


def show_bytes(root: str, rev: str, path: str) -> bytes | None:
    proc = subprocess.run(["git", "-C", root, "show", f"{rev}:{path}"],
                          stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=clean_env())
    return proc.stdout if proc.returncode == 0 else None


def parse_registry(text: str) -> dict[str, list[str]]:
    """Census-parser behaviour: 0 to 3 leading spaces before the pipe, under `## Registry`."""
    rows: dict[str, list[str]] = {}
    in_registry = False
    for line in text.splitlines():
        if line.strip().startswith("## "):
            in_registry = line.strip().lower().startswith("## registry")
            continue
        if not in_registry or not re.match(r"^ {0,3}\|", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 2 and re.fullmatch(r"S[0-9]{3,}", cells[0]):
            rows[cells[0]] = cells
    return rows


def row_lines(text: str) -> dict[str, str]:
    """First registry-table line per id, scoped to `## Registry` like parse_registry."""
    out: dict[str, str] = {}
    in_registry = False
    for line in text.split("\n"):
        if line.strip().startswith("## "):
            in_registry = line.strip().lower().startswith("## registry")
            continue
        if not in_registry:
            continue
        m = re.match(ROW_RE % r"S[0-9]{3,}", line)
        if m and m.group(1) not in out:
            out[m.group(1)] = line
    return out


def used_by(cell: str) -> list[str]:
    return [p.strip() for p in re.split(r"[,;]", cell) if p.strip() and p.strip() != "—"]


def units(text: str) -> int:
    """One unit per CJK character, one per non-CJK whitespace token."""
    return len(CJK_RE.findall(text)) + len([t for t in text.split() if not CJK_RE.search(t)])


def content_window(text: str, sid: str) -> tuple[int, int] | None:
    """The article block: from the page's identity/byline container to the end marker (header, navigation, sidebar, promo and footer excluded)."""
    lo = text.find(ARTICLE_START[sid])
    if lo < 0:
        return None
    hi = text.find(ARTICLE_END[sid], lo + 1)
    return (lo, hi) if hi > lo else None


def text_segments(text: str, sid: str) -> list[str]:
    """Text nodes of the article block (tags, attribute values and <style>/<script> bodies are not text): a span qualifies only when it lies
    inside one of them, as written (entities are not decoded)."""
    win = content_window(text, sid)
    if win is None:
        return []
    chunk = re.sub(r"(?is)<(style|script)\b.*?</\1>", "<>", text[win[0]:win[1]])
    return re.findall(r">([^<>]+)(?=<)", chunk)


def article_headings(text: str, sid: str) -> list[str]:
    """The <h2>/<h3> texts of the article block, inner tags removed, whitespace collapsed."""
    win = content_window(text, sid)
    if win is None:
        return []
    return [re.sub(r"\s+", " ", re.sub(r"<[^>]*>", "", h)).strip()
            for h in re.findall(r"(?is)<h[23]\b[^>]*>(.*?)</h[23]>", text[win[0]:win[1]])]


def in_content(text: str, span: str, sid: str) -> bool:
    """True when `span` is a raw substring of one text node of the article block."""
    return any(span in seg for seg in text_segments(text, sid))


def gate_lines(lesson: str) -> list[str]:
    out, in_gate = [], False
    for line in lesson.splitlines():
        if line.strip().startswith("## "):
            in_gate = line.strip().lower() == "## gate"
            continue
        if in_gate:
            out.append(line)
    return out


def gate_line(lesson: str, sid: str) -> str | None:
    for line in gate_lines(lesson):
        if line.strip().startswith(f"- {sid} "):
            return line
    return None


def parse_iso(value) -> datetime | None:
    if not isinstance(value, str):
        return None
    try:
        stamp = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None
    return stamp if stamp.tzinfo else None


def row_url(row: list[str]) -> str | None:
    for token in reversed(row[1].split()) if len(row) > 1 else []:
        if token.startswith(("http://", "https://")):
            return token
    return None


def set_used_by(line: str, value: str) -> str:
    """Replace the last data cell (used-by) of a registry row line."""
    head, _, _tail = line.rstrip().rstrip("|").rpartition("|")
    return f"{head}| {value} |"


