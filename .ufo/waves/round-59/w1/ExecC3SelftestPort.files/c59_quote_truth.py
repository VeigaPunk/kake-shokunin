def main() -> int:
    class _Parser(argparse.ArgumentParser):
        def error(self, message):
            print(f"usage error: {message}", file=sys.stderr)
            raise SystemExit(64)

    ap = _Parser(description="Round-59 C3 counter (crawler-identity correction + Google crawler-identity entries)")
    ap.add_argument("--root", default=".")
    ap.add_argument("--base", default=BASE_REV, help="the base revision holding the pre-append registry (default: the frozen one)")
    ap.add_argument("--revision")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    if not args.revision:
        print("usage: --revision is required unless --selftest is used", file=sys.stderr)
        return 64
    # D2 (round-58 spot-check, SentinelCounters F3/F4/F6): both revisions resolved once to commit ids; the root is the toplevel
    rc_top, top = git(args.root, "rev-parse", "--show-toplevel")
    if rc_top != 0 or os.path.realpath(top.strip()) != os.path.realpath(args.root):
        print(f"unevaluable: --root {args.root!r} is not the toplevel of a git repository")
        print("EXIT=2")
        return 2
    rc_r, rev_id = git(args.root, "rev-parse", "--verify", "--quiet", f"{args.revision}^{{commit}}")
    rc_b, base_id = git(args.root, "rev-parse", "--verify", "--quiet", f"{args.base}^{{commit}}") if args.base else (1, "")
    if rc_r != 0 or rc_b != 0:
        print(f"unevaluable: revision {args.revision!r} or base {args.base!r} does not resolve to a commit in {args.root!r}")
        print("EXIT=2")
        return 2
    args.revision = rev_id.strip()
    code, results = run_checks(args.root, args.revision, base_id.strip())
    passed = sum(1 for r in results if r["state"] == "pass")
    if args.json:
        print(json.dumps({
            "schema": "kake-r59-c3-quote-truth-v1", "predicate": PREDICATE, "revision": args.revision,
            "adopted": ADOPTED,
            "checks": {r["check"]: {"passed": r["state"] == "pass", "state": r["state"],
                                    "notes": r["notes"], "facts": r["facts"]} for r in results},
            "conditions_passed": passed, "exit": code, "met": code == 0}, indent=1, ensure_ascii=False))
        return code
    else:
        print(f"C3 quote-truth {passed}/9 met={code == 0}  ({PREDICATE})")
        for r in results:
            print(f"  {r['check']} {r['state'].upper()}")
            for note in r["notes"]:
                print(f"    - {note}")
        print(f"  revision: {args.revision}")
    print(f"EXIT={code}")
    return code


if __name__ == "__main__":
    sys.exit(main())
