def _bullet_end(bl: list, s: int) -> int:
    """Where the stale bullet ends: the next base line that is blank or opens another list item (the counter's rule)."""
    end = s + 1
    while end < len(bl) and bl[end].strip() and not re.match(r"^\s{0,3}[-*+] ", bl[end]):
        end += 1
    return end


def _stale_measured(base_text: str, tail: list) -> str:
    """Base document plus the correction tail, inserted exactly where the stale bullet ends."""
    bl = base_text.split("\n")
    if STALE_LINE not in bl:
        return base_text
    at = _bullet_end(bl, bl.index(STALE_LINE))
    return "\n".join(bl[:at] + list(tail) + bl[at:])


def _long_bullet_base(base_text: str) -> str:
    """A base document whose stale bullet runs twelve continuation lines: its end is outside the 8-line window."""
    bl = base_text.split("\n")
    if STALE_LINE not in bl:
        return base_text
    s = bl.index(STALE_LINE)
    end = _bullet_end(bl, s)
    filler = [f"  fixture continuation {i} that keeps the stale bullet open" for i in range(1, 13)]
    return "\n".join(bl[:s + 1] + filler + bl[end:])


def _short_bullet_base(base_text: str) -> str:
    """A base document whose stale bullet ends on its own line (no continuation lines)."""
    bl = base_text.split("\n")
    if STALE_LINE not in bl:
        return base_text
    s = bl.index(STALE_LINE)
    end = _bullet_end(bl, s)
    return "\n".join(bl[:s + 1] + bl[end:])


def _build(files: dict, pre_keys: set) -> tuple:
    """Sandbox repo: base-revision registry + base stale document, pre-append evidence, then the append."""
    d = tempfile.mkdtemp(prefix="c59-qt-", dir=_selftest_tmp())
    subprocess.run(["git", "-C", d, "init", "-q"], check=True)
    rc, top = git(d, "rev-parse", "--show-toplevel")
    if rc != 0 or os.path.realpath(top.strip()) != os.path.realpath(d):
        raise RuntimeError("fixture repo toplevel mismatch")

    def commit(batch: dict, msg: str) -> str:
        for rel, text in batch.items():
            tgt = os.path.join(d, rel)
            os.makedirs(os.path.dirname(tgt), exist_ok=True)
            with open(tgt, "w", encoding="utf-8", newline="") as fh:
                fh.write(text)
        subprocess.run(["git", "-C", d, "add", "-A"], check=True)
        subprocess.run(["git", "-C", d, "-c", "user.name=selftest", "-c", "user.email=selftest@local",
                        "commit", "-q", "--allow-empty", "-m", msg], check=True)
        return git(d, "rev-parse", "HEAD")[1].strip()

    commit({REGISTRY: files.get("__base_registry__", ""), STALE_PATH: files.get("__base_stale__", "")}, "base")
    base_sha = git(d, "rev-parse", "HEAD")[1].strip()
    commit({k: v for k, v in files.items() if k in pre_keys}, "pre-append evidence")
    tip = commit({k: v for k, v in files.items() if k not in pre_keys and not k.startswith("__base_")}, "append")
    return d, tip, base_sha


