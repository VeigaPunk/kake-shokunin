    if rc != 0:
        reasons.append(f"exit={rc}")
    out.append(("Q6_selftest_tally_is_independently_verified", not reasons,
                "; ".join(reasons) if reasons else f"tally={m[-1] if m else None} case_lines={len(case_lines)}"))
    return out


