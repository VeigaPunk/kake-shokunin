#!/usr/bin/env python3
"""Build round-98 C2 control subjects into frozen/ (run once before freeze).

pos-oracle.py      the counter's oracle as a standalone CLI (main-path proof)
neg-constant.py    always `revalidate`, never refuses
neg-lookup.py      memorized hand-case answers, `revalidate` otherwise
neg-noprohibit.py  oracle with the RFC 9111 prohibitions removed
neg-exclusive.py   oracle with exclusive window boundaries
neg-respsie.py     oracle that ignores the request stale-if-error
neg-lenient.py     oracle that never refuses a malformed Cache-Control field
"""
import json, os, re, sys
W = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(W, "c98_stale.py")).read()
orc = src[src.index("class Refuse"):src.index("# ---------------------------------------------------------------- hand cases")]
head = src[src.index("CLAMP ="):src.index("class Refuse")]
CLI = '''

def _main():
    import json, sys
    try:
        inp = json.loads(sys.stdin.read())
        out = decide(inp)
    except (Refuse, ValueError) as e:
        sys.stderr.write("invalid_input: %s\\n" % e)
        return 1
    sys.stdout.write(json.dumps(out) + "\\n")
    return 0


if __name__ == "__main__":
    sys.exit(_main())
'''
base = "#!/usr/bin/env python3\n# round-98 control subject (generated by build_frozen.py)\nimport json, sys\n" + head + orc
F = os.path.join(W, "frozen"); os.makedirs(F, exist_ok=True)


def put(name, text):
    open(os.path.join(F, name), "w").write(text)


def sub(text, a, b):
    assert a in text, a
    return text.replace(a, b)


put("pos-oracle.py", base + CLI)
put("neg-noprohibit.py", sub(base, "    prohibited = (", "    prohibited = False and (") + CLI)
put("neg-exclusive.py", sub(sub(base, "st <= w", "st < w"), "st <= e", "st < e") + CLI)
put("neg-respsie.py", sub(base, '    e = delta(qc, "stale-if-error")\n', "    e = None\n") + CLI)
put("neg-lenient.py", sub(base, "    rc, qc = parse_cc(rc_s), parse_cc(qc_s)",
                          "    def _p(s):\n        try:\n            return parse_cc(s)\n        except Refuse:\n            return {}\n"
                          "    rc, qc = _p(rc_s), _p(qc_s)") + CLI)
put("neg-constant.py", '''#!/usr/bin/env python3
import json, sys
d = json.loads(sys.stdin.read())
try:
    st = max(0, int(d["current_age"]) - int(d["freshness_lifetime"]))
except Exception:
    st = 0
print(json.dumps({"decision": "revalidate", "staleness": st}))
''')
sys.path.insert(0, W)
import c98_stale as c  # noqa: E402
table = {}
for hid, tag, inp, want in c.HAND:
    table[json.dumps(inp, sort_keys=True)] = want
put("neg-lookup.py", '''#!/usr/bin/env python3
import json, sys
T = json.loads(%r)
raw = sys.stdin.read()
try:
    d = json.loads(raw)
    k = json.dumps(d, sort_keys=True)
except ValueError:
    d, k = {}, ""
w = T.get(k)
if w == "REFUSE":
    sys.stderr.write("invalid_input: memorized\\n"); sys.exit(1)
if w:
    print(json.dumps({"decision": w[0], "staleness": w[1]})); sys.exit(0)
try:
    st = max(0, int(d["current_age"]) - int(d["freshness_lifetime"]))
except Exception:
    st = 0
print(json.dumps({"decision": "revalidate", "staleness": st}))
''' % json.dumps(table))
print("built", sorted(os.listdir(F)))
